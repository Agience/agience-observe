using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace Agience.Core;

/// <summary>
/// Renders the Caddyfile that fronts this node, from the instances the manager already holds.
/// </summary>
/// <remarks>
/// <para>
/// ⭐ GENERATED RATHER THAN SHIPPED, BECAUSE THE FACTS ARE ALREADY HERE. Every site block needs a
/// name and an upstream port, and <see cref="AgienceConfig"/> knows both for every instance. A
/// hand-maintained Caddyfile beside it would be a second copy of the port table, and the failure
/// when they drift is a certificate that resolves to the wrong service — valid TLS, wrong data, no
/// error anywhere.
/// </para>
/// <para>
/// ⛔ THAT IS NOT HYPOTHETICAL — IT HAPPENED, WITHIN A DAY. A hand-written Caddyfile was kept beside
/// the node's own configuration while this was being built. Measured 2026-09-16 by comparing the
/// two: the generated file had **seven** site blocks and the hand-written one **five**. It was
/// missing `chorus.` and `ember.`, so the wildcard caught them and sent
/// <c>ember.home.agience.ai</c> to **8087** — the persona host — instead of to Ember on 8091. A
/// valid certificate in front of the wrong service, answering normally, with nothing to notice.
/// </para>
/// <para>
/// The hand-written copy was deleted rather than corrected. Nothing referenced it, and a duplicate
/// that has already drifted once will drift again; this class derives every name and port from the
/// instance list and cannot acquire that defect.
/// </para>
/// <para>
/// ⛔ EVERY SITE BINDS 127.0.0.1, AND THAT IS THE WHOLE REASON THIS FILE IS TESTED. Caddy's default
/// is every interface. Measured 2026-09-16 on this machine: an edge written without <c>bind</c>
/// listened on <c>::</c> for every name on the node while all five Python services were correctly
/// on loopback — so adding TLS had quietly published them to whatever network the laptop next
/// joined. <c>ServiceCatalogTests.No_kind_binds_a_public_interface</c> cannot see this, because a
/// native kind declares its address in a config file rather than on a command line. This is where
/// that invariant is actually held.
/// </para>
/// <para>
/// ⚠ THE NAMES RESOLVE TO LOOPBACK ANYWAY. <c>*.home.agience.ai</c> is published as 127.0.0.1 in
/// public DNS, so binding loopback costs nothing: the only machine that can reach these names is
/// this one.
/// </para>
/// <para>
/// ⚠ <c>tls internal</c>, NOT A PUBLIC CERTIFICATE. Per-node issuance from Caddy's own CA, which is
/// what lets trust scope equal reachability scope and removes any renewal schedule. The root is
/// installed once by the installer, elevated; see the notes on the trust step.
/// </para>
/// </remarks>
public static class EdgeConfig
{
    /// <summary>The file name the edge is started with — relative, so it resolves against the
    /// instance's working directory.</summary>
    public const string FileName = "Caddyfile";

    /// <summary>
    /// Render the Caddyfile for <paramref name="config"/>, or null when no edge is warranted.
    /// </summary>
    /// <remarks>
    /// Null rather than an empty string when there is nothing to front: an empty Caddyfile is a
    /// valid configuration that serves nothing, so writing one would start an edge that answers
    /// every request with a connection refused and looks like a crashed service.
    /// </remarks>
    public static string? Render(AgienceConfig config)
    {
        if (config is null)
        {
            throw new ArgumentNullException(nameof(config));
        }

        // The edge fronts the OTHER services; it never fronts itself.
        var fronted = config.Instances
            .Where(i => i.Enabled)
            .Where(i => i.Definition is not null && i.Definition.Executable is null)
            .Where(i => !string.IsNullOrWhiteSpace(i.Domain))
            .Where(i => !string.IsNullOrWhiteSpace(i.Definition!.Subdomain))
            .ToList();

        if (fronted.Count == 0)
        {
            return null;
        }

        var sb = new StringBuilder();
        // ⚠ NO BLANK LINE BEFORE THE GLOBAL BLOCK. `caddy fmt` treats one as an inconsistency and
        // every start then logs "Caddyfile input is not formatted" — a warning on a generated file
        // that nobody can act on, which is how people learn to skim warnings.
        sb.AppendLine("# GENERATED by Agience.Core.EdgeConfig — edits are overwritten.");
        sb.AppendLine("# The ports below come from manager.json; change them there, not here.");
        sb.AppendLine("{");
        sb.AppendLine("\tadmin off");
        sb.AppendLine("}");

        foreach (var instance in fronted.OrderBy(i => i.Definition!.Subdomain, StringComparer.Ordinal))
        {
            var host = instance.Definition!.Subdomain + "." + instance.Domain.Trim().Trim('.');
            AppendSite(sb, host, instance.Port);
        }

        // The apex and every other name under the domain go to the host router, which does its own
        // routing from the Host header — so persona names need no block of their own.
        var router = fronted.FirstOrDefault(i =>
            string.Equals(i.Kind, ServiceCatalog.Chorus.Name, StringComparison.OrdinalIgnoreCase));

        if (router is not null)
        {
            var domain = router.Domain.Trim().Trim('.');
            AppendSite(sb, domain, router.Port);
            AppendSite(sb, "*." + domain, router.Port);
        }

        return sb.ToString();
    }

    private static void AppendSite(StringBuilder sb, string host, int port)
    {
        sb.AppendLine();
        sb.AppendLine(host + " {");
        sb.AppendLine("\tbind 127.0.0.1");
        sb.AppendLine("\ttls internal");

        // `flush_interval -1` disables response buffering. `/mcp` is MCP over Streamable HTTP, and a
        // buffering proxy turns a server-initiated stream into one delivery at the end — which
        // presents as a hang rather than as an error.
        sb.AppendLine("\treverse_proxy 127.0.0.1:" + port.ToString(CultureInfo.InvariantCulture) + " {");
        sb.AppendLine("\t\tflush_interval -1");
        sb.AppendLine("\t}");
        sb.AppendLine("\tencode gzip");
        sb.AppendLine("}");
    }
}
